"""Build NH Site Docs from its one source file, NH-Site-Docs-Shared.html.

Outputs
  app/                        the installable app (upload this whole folder to the web host)
    index.html                the app
    manifest.webmanifest      name, icon and colours used when the app is installed
    sw.js                     offline support: keeps the app working without internet
    icon-192.png, icon-512.png, apple-touch-icon.png
    config.js                 connection settings (created once; your edits are never overwritten)
  NH-Site-Docs-Offline.html   a single-device copy with no server, for emergencies

NH-Site-Docs-Shared.html is also what the claude.ai page publishes.

Run:  python build.py
Then upload the app/ folder to the web host (see SETUP.md). Code.gs is pasted into Apps Script separately.
"""
import hashlib
import json
import pathlib
import struct
import zlib

here = pathlib.Path(__file__).resolve().parent
src = (here / 'NH-Site-Docs-Shared.html').read_text(encoding='utf-8')
app = here / 'app'
app.mkdir(exist_ok=True)

BRAND = (0x1d, 0x23, 0x60)
CREAM = (0xf8, 0xf4, 0xe9)

# ---------- the single-device offline copy ----------
plain_head = ('<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
              '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n</head>\n<body>\n')
(here / 'NH-Site-Docs-Offline.html').write_text(plain_head + src + '\n</body>\n</html>\n', encoding='utf-8')
print('Wrote NH-Site-Docs-Offline.html')

# ---------- the installable app ----------
app_head = ('<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
            '<meta name="theme-color" content="#1d2360">\n'
            '<meta name="mobile-web-app-capable" content="yes">\n'
            '<meta name="apple-mobile-web-app-capable" content="yes">\n'
            '<meta name="apple-mobile-web-app-title" content="NH Site Docs">\n'
            '<link rel="manifest" href="manifest.webmanifest">\n'
            '<link rel="icon" type="image/png" href="icon-192.png">\n'
            '<link rel="apple-touch-icon" href="apple-touch-icon.png">\n'
            '<script src="config.js"></script>\n'
            '</head>\n<body>\n')
index = app_head + src + '\n</body>\n</html>\n'
(app / 'index.html').write_text(index, encoding='utf-8')

cfg = app / 'config.js'
if not cfg.exists():
    cfg.write_text(
        "/* NH Site Docs: connection settings. Fill these in during setup (see SETUP.md). */\n"
        "window.NH_CONFIG = {\n"
        "  apiUrl: '',     // Apps Script web app URL, ending in /exec\n"
        "  clientId: '',   // Google OAuth Web client ID, ending in .apps.googleusercontent.com\n"
        "  domain: '12neighbours.com'  // only accounts from this Google Workspace domain can sign in\n"
        "};\n", encoding='utf-8')
    print('Created app/config.js (fill it in)')

manifest = {
    "name": "NH Site Docs",
    "short_name": "NH Site Docs",
    "description": "Shift documentation for 12 Neighbours Neighbourly Homes sites.",
    "start_url": "./",
    "scope": "./",
    "display": "standalone",
    "orientation": "any",
    "background_color": "#f8f4e9",
    "theme_color": "#1d2360",
    "icons": [
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}
(app / 'manifest.webmanifest').write_text(json.dumps(manifest, indent=2), encoding='utf-8')

version = hashlib.sha1(index.encode('utf-8')).hexdigest()[:10]
sw = """/* NH Site Docs offline support. Generated by build.py; version changes with every build. */
const VERSION = 'nh-%s';
const SHELL = ['./', './index.html', './config.js', './manifest.webmanifest', './icon-192.png', './icon-512.png', './icon-maskable-512.png', './apple-touch-icon.png'];
const CDN = ['https://cdnjs.cloudflare.com/ajax/libs/xlsx/0.18.5/xlsx.full.min.js'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(SHELL).then(() =>
    Promise.all(CDN.map(u => fetch(u, { mode: 'no-cors' }).then(r => c.put(u, r)).catch(() => {}))))));
  self.skipWaiting();
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;                  // app data goes to the server (POST) and is never cached here
  const url = new URL(req.url);
  if (url.origin === location.origin) {
    const shell = req.mode === 'navigate' || url.pathname.endsWith('/config.js') || url.pathname.endsWith('/index.html');
    if (shell) {                                       // network first, so updates arrive; cached copy when offline
      const key = req.mode === 'navigate' ? './index.html' : req;
      e.respondWith(fetch(req).then(r => { if (r.ok) { const copy = r.clone(); caches.open(VERSION).then(c => c.put(key, copy)); } return r; })
        .catch(() => caches.match(key)));
    } else {
      e.respondWith(caches.match(req).then(r => r || fetch(req)));
    }
  } else if (CDN.includes(url.href)) {
    e.respondWith(caches.match(url.href).then(r => r || fetch(req)));
  }
});
""" % version
(app / 'sw.js').write_text(sw, encoding='utf-8')


# ---------- icons (drawn here so there is nothing else to install) ----------
def png(path, size):
    def inside_house(x, y):
        # coordinates in 0..1, content kept inside the central 70% so it survives icon masks
        roof_top, roof_base, body_bottom = 0.22, 0.48, 0.78
        if roof_top <= y <= roof_base:
            half = 0.30 * (y - roof_top) / (roof_base - roof_top)
            return abs(x - 0.5) <= half
        if roof_base < y <= body_bottom and 0.28 <= x <= 0.72:
            door = 0.44 <= x <= 0.56 and y >= 0.60
            return not door
        return False
    rows = []
    for py in range(size):
        row = bytearray([0])
        for px in range(size):
            # 2x2 supersampling for smooth edges
            hits = sum(inside_house((px + dx) / size, (py + dy) / size) for dx in (0.25, 0.75) for dy in (0.25, 0.75))
            a = hits / 4
            row += bytes(round(BRAND[i] * (1 - a) + CREAM[i] * a) for i in range(3))
        rows.append(bytes(row))
    raw = b''.join(rows)

    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    data = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    path.write_bytes(data)


# The real icons are made from the 12 Neighbours logo (assets/12n-logo.png) and committed in app/.
# These plain house icons are only a fallback if an icon file is ever missing.
for name, size in (('icon-192.png', 192), ('icon-512.png', 512), ('icon-maskable-512.png', 512), ('apple-touch-icon.png', 180)):
    if not (app / name).exists():
        png(app / name, size)
print('Wrote app/ (index.html, manifest, sw.js, icons) · version', version)
